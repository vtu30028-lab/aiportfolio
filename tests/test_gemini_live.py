"""
PortfolioAI - Gemini API Live Integration Test
Checks live API connectivity and content generation when network is available.
"""

import os
import requests
import pytest
from dotenv import load_dotenv

load_dotenv()


def test_gemini_api_key_configured():
    """Verify that GEMINI_API_KEY is defined and not using default placeholder."""
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    assert api_key, "GEMINI_API_KEY is not set in environment or .env."
    assert api_key != "your_gemini_api_key_here", "GEMINI_API_KEY is still set to placeholder."
    assert len(api_key) > 20, "GEMINI_API_KEY appears suspiciously short."


def test_gemini_live_generation():
    """Verify live connectivity and content generation with Google Gemini API."""
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not api_key or api_key == "your_gemini_api_key_here":
        pytest.skip("Skipping live test: GEMINI_API_KEY not configured.")

    model = os.environ.get("GEMINI_MODEL", "gemini-3.5-flash-lite").strip()
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
    payload = {
        "contents": [{"parts": [{"text": "Reply with ONE word: 'VERIFIED'"}]}]
    }

    try:
        response = requests.post(url, json=payload, timeout=15)
    except requests.exceptions.ConnectionError:
        pytest.skip("Skipping live test: No network access to generativelanguage.googleapis.com.")

    assert response.status_code == 200, f"Gemini API returned HTTP {response.status_code}: {response.text}"
    data = response.json()
    candidates = data.get("candidates", [])
    assert len(candidates) > 0, "No candidates returned by Gemini API."
    text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
    assert text, "Empty text generated by Gemini."
