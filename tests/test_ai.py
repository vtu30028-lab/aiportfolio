# 3. Invalid and oversized input rejection
def test_invalid_and_oversized_input_rejected(client, app):
    """Test that missing required fields and oversized payloads are rejected with 400 Bad Request."""
    create_and_login_user(client, app, name="Input Tester", email="input@test.com")
    csrf_token = extract_csrf_token(client.get("/ai/"))
    headers = {"X-CSRFToken": csrf_token, "Content-Type": "application/json"}

    # Missing skills
    res_no_skills = client.post(
        "/ai/generate-summary",
        headers=headers,
        json={"name": "Input Tester", "skills": ""},
    )
    assert res_no_skills.status_code == 400
    assert "technical skills" in res_no_skills.get_json()["error"]

    # Oversized payload (> 1500 chars)
    oversized_text = "Python, " * 400
    res_oversized = client.post(
        "/ai/generate-summary",
        headers=headers,
        json={"name": "Input Tester", "skills": oversized_text},
    )
    assert res_oversized.status_code == 400
    assert "character limit" in res_oversized.get_json()["error"]


